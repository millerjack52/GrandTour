"""Package the approved H2 loops losslessly for the native renderer (no UE import)."""
from pathlib import Path
import hashlib, json, shutil, struct
import numpy as np
from scipy.io import wavfile
from scipy import signal

root = Path(__file__).resolve().parents[2]
source = root/'Art/Export/VehicleAudio/RangeRover_Hybrid_H2_final'
dest = root/'Content/Audio/RangeRoverHybridH2'
dest.mkdir(parents=True, exist_ok=True)
manifest = json.loads((source/'manifest.json').read_text())
data = bytearray(struct.pack('<4I', 0x32485447, 1, 48000, 4))
hashes = {}
for bank in manifest['loop_bank']:
    path = source/'PreparedLoops'/(bank['name']+'.wav')
    rate, samples = wavfile.read(path)
    assert rate == 48000 and samples.dtype == np.float32 and samples.shape[1] == 2
    assert np.isfinite(samples).all() and len(samples) == bank['period_samples']
    data.extend(struct.pack('<fI', bank['root_rpm'], len(samples)))
    data.extend(samples.astype('<f4').tobytes())
    hashes[path.name] = hashlib.sha256(path.read_bytes()).hexdigest()
(dest/'loops.gth2').write_bytes(data)
shutil.copyfile(source/'ATTRIBUTION.txt', dest/'ATTRIBUTION.txt')
(dest/'provenance.json').write_text(json.dumps(dict(version='H2-runtime-1',
    sources=manifest['source_provenance'], prepared_loop_hashes=hashes,
    binary_sha256=hashlib.sha256(data).hexdigest(), profile=manifest['profile']), indent=2))
coeff = '// Generated by Art/tools/prepare_range_rover_h2_runtime.py from the approved H2 calibration.\n#pragma once\n'
coeff += f'constexpr double H2MasterGain = {manifest["shared_gain"]:.17g};\n'
coeff += f'constexpr double H2SupportGain = {manifest["shared_support_gain"]:.17g};\n'
for name, sos in [('H2HighPass', signal.butter(2, 29, btype='highpass', fs=48000, output='sos')),
                  ('H2SupportFilter', signal.butter(4, [32,125], btype='bandpass', fs=48000, output='sos'))]:
    coeff += f'constexpr double {name}[{len(sos)}][6] = {{\n'
    coeff += ''.join('    {'+', '.join(f'{v:.17g}' for v in row)+'},\n' for row in sos)
    coeff += '};\n'
(root/'Source/GrandTour/Vehicle/GTRangeRoverH2Coefficients.h').write_text(coeff)
print(f'Packaged {len(data)} bytes; original audition files unchanged.')
